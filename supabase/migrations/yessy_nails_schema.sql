-- ================================================================
-- 1. TABLAS
-- ================================================================

-- ----------------------------------------------------------------
-- configuracion_sitio — Configuración dinámica del sitio (1 fila)
-- ----------------------------------------------------------------
CREATE TABLE configuracion_sitio (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo_banner               VARCHAR(255) NOT NULL DEFAULT 'Yessy Nails',
    subtitulo_banner            VARCHAR(500),
    imagen_banner_url           VARCHAR(500),
    promo_mes_titulo            VARCHAR(255),
    promo_mes_texto             TEXT,
    telefono_whatsapp           VARCHAR(20),
    direccion_texto             VARCHAR(500),
    latitud                     NUMERIC(10,7),
    longitud                    NUMERIC(10,7),
    horario_atencion            VARCHAR(255),
    bio_yessica                 TEXT,
    anos_experiencia            INTEGER DEFAULT 0,
    titular_transferencia       VARCHAR(255),
    clabe_transferencia         VARCHAR(18),
    banco_transferencia         VARCHAR(100),
    auto_cancelar_sin_confirmar BOOLEAN NOT NULL DEFAULT false,
    horas_limite_confirmacion   INTEGER NOT NULL DEFAULT 24
);

-- ----------------------------------------------------------------
-- clientes — Registro de clientas del salón
-- ----------------------------------------------------------------
CREATE TABLE clientes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre             VARCHAR(255) NOT NULL,
    correo             VARCHAR(255) NOT NULL UNIQUE,
    telefono           VARCHAR(20),
    acepta_promociones BOOLEAN NOT NULL DEFAULT true,
    fecha_registro     TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------
-- servicios — Catálogo de servicios del salón
-- ----------------------------------------------------------------
CREATE TABLE servicios (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(255) NOT NULL,
    categoria        VARCHAR(100) NOT NULL CHECK (categoria IN (
                         'Acrílico', 'Gelish', 'Soft Gel', 'Polygel',
                         'Retiro/Mantenimiento', 'Pedicure/Spa', 'Cejas'
                     )),
    descripcion      TEXT,
    precio_base      NUMERIC(10,2) NOT NULL,
    duracion_minutos INTEGER NOT NULL,
    imagen_url       VARCHAR(500)
);

-- ----------------------------------------------------------------
-- portafolio — Galería de trabajos realizados
-- ----------------------------------------------------------------
CREATE TABLE portafolio (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(255) NOT NULL,
    estilo         VARCHAR(100) NOT NULL CHECK (estilo IN (
                       'Minimalista', '3D', 'Francés', 'Temporada'
                   )),
    descripcion    TEXT,
    imagen_url     VARCHAR(500),
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------
-- citas — Agendado de citas con clientas
-- ----------------------------------------------------------------
CREATE TABLE citas (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id                  BIGINT REFERENCES clientes(id) ON DELETE SET NULL,
    nombre_cliente              VARCHAR(255) NOT NULL,
    correo_cliente              VARCHAR(255),
    telefono_cliente            VARCHAR(20) NOT NULL,
    servicio_id                 BIGINT NOT NULL REFERENCES servicios(id),
    fecha_cita                  DATE NOT NULL,
    hora_cita                   TIME NOT NULL,
    notas_diseno                TEXT,
    total_estimado              NUMERIC(10,2),
    anticipo_requerido          NUMERIC(10,2) NOT NULL DEFAULT 50,
    metodo_pago                 VARCHAR(30) DEFAULT 'efectivo' CHECK (metodo_pago IN (
                                    'efectivo', 'transferencia', 'pasarela_futura'
                                )),
    folio_transferencia         VARCHAR(100),
    estado_confirmacion_cliente VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado_confirmacion_cliente IN (
                                    'pendiente', 'respondido'
                                )),
    estado_cita                 VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado_cita IN (
                                    'pendiente', 'confirmada', 'completada', 'cancelada'
                                )),
    estado_pago                 VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado_pago IN (
                                    'pendiente', 'anticipo_50', 'pagado'
                                )),
    fecha_creacion              TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------
-- pedidos — Pedidos de productos / entregas a domicilio
-- ----------------------------------------------------------------
CREATE TABLE pedidos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        BIGINT REFERENCES clientes(id) ON DELETE SET NULL,
    nombre_cliente    VARCHAR(255) NOT NULL,
    correo_cliente    VARCHAR(255),
    telefono_cliente  VARCHAR(20),
    items_json        JSONB NOT NULL DEFAULT '[]'::jsonb,
    total             NUMERIC(10,2) NOT NULL DEFAULT 0,
    tipo_entrega      VARCHAR(30) NOT NULL DEFAULT 'estudio' CHECK (tipo_entrega IN (
                          'estudio', 'punto_medio_domicilio'
                      )),
    direccion_entrega TEXT,
    lat_entrega       NUMERIC(10,7),
    lng_entrega       NUMERIC(10,7),
    estado_pedido     VARCHAR(20) NOT NULL DEFAULT 'pendiente' CHECK (estado_pedido IN (
                          'pendiente', 'confirmado', 'entregado', 'cancelado'
                      )),
    fecha_creacion    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ----------------------------------------------------------------
-- mensajes_chat — Mensajería entre clientas y Yessica
-- ----------------------------------------------------------------
CREATE TABLE mensajes_chat (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sala_cliente_id  VARCHAR(100) NOT NULL,
    nombre_remitente VARCHAR(255) NOT NULL,
    rol              VARCHAR(20) NOT NULL CHECK (rol IN ('cliente', 'yessica')),
    mensaje          TEXT NOT NULL,
    fecha_envio      TIMESTAMPTZ NOT NULL DEFAULT now(),
    leido            BOOLEAN NOT NULL DEFAULT false
);

-- ================================================================
-- 2. ÍNDICES
-- ================================================================
CREATE INDEX idx_servicios_categoria ON servicios (categoria);
CREATE INDEX idx_portafolio_estilo   ON portafolio (estilo);
CREATE INDEX idx_citas_fecha         ON citas (fecha_cita);
CREATE INDEX idx_citas_servicio      ON citas (servicio_id);
CREATE INDEX idx_citas_cliente       ON citas (cliente_id);
CREATE INDEX idx_pedidos_cliente     ON pedidos (cliente_id);
CREATE INDEX idx_mensajes_sala       ON mensajes_chat (sala_cliente_id);
CREATE INDEX idx_mensajes_fecha      ON mensajes_chat (fecha_envio);

-- ================================================================
-- 3. SEGURIDAD (RLS)
-- ----------------------------------------------------------------
-- Estrategia:
--   * Lectura pública (anon) solo del contenido del sitio: configuración,
--     servicios y portafolio.
--   * Escritura de citas, pedidos, clientes y mensajes se realiza desde
--     el backend Express con la llave service_role (omite RLS).
--   * Los usuarios autenticados (panel admin de Supabase Auth) tienen
--     acceso total.
--   * Todo lo demás queda denegado por defecto.
-- ================================================================

ALTER TABLE configuracion_sitio ENABLE ROW LEVEL SECURITY;
ALTER TABLE clientes            ENABLE ROW LEVEL SECURITY;
ALTER TABLE servicios           ENABLE ROW LEVEL SECURITY;
ALTER TABLE portafolio          ENABLE ROW LEVEL SECURITY;
ALTER TABLE citas               ENABLE ROW LEVEL SECURITY;
ALTER TABLE pedidos             ENABLE ROW LEVEL SECURITY;
ALTER TABLE mensajes_chat       ENABLE ROW LEVEL SECURITY;

-- Lectura pública del contenido del sitio
CREATE POLICY "public_read_config"    ON configuracion_sitio FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public_read_servicios" ON servicios           FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "public_read_portafolio" ON portafolio         FOR SELECT TO anon, authenticated USING (true);

-- Acceso total para el panel admin (usuarios autenticados)
CREATE POLICY "auth_all_config"    ON configuracion_sitio FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_clientes"  ON clientes            FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_servicios" ON servicios           FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_portafolio" ON portafolio         FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_citas"     ON citas               FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_pedidos"   ON pedidos             FOR ALL TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "auth_all_mensajes"  ON mensajes_chat       FOR ALL TO authenticated USING (true) WITH CHECK (true);

-- Permisos base (Supabase ya otorga estos por defecto; se dejan explícitos)
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES    IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

